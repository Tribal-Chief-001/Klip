use crate::driver::{
    CapturedClip, ClipboardDriver, EchoShield, PlatformEnvironment, PlatformError,
};
use arboard::Clipboard;
use klip_proto::hlc::NodeId;
use klip_proto::wire::{compute_fingerprint, ClipContentType};
use std::sync::atomic::AtomicI64;
use std::sync::Mutex;

pub const CONCEALED_TYPE: &str = "org.nspasteboard.ConcealedType";
pub const AUTO_GENERATED_TYPE: &str = "org.nspasteboard.AutoGeneratedType";
pub const ONE_PASSWORD_TYPE: &str = "com.agilebits.onepassword";

#[allow(dead_code)]
pub struct MacOSClipboardDriver {
    clipboard: Mutex<Option<Clipboard>>,
    last_change_count: AtomicI64,
    echo_shield: EchoShield,
    local_node: NodeId,
}

impl MacOSClipboardDriver {
    pub fn new(local_node: NodeId) -> Self {
        let clipboard = Mutex::new(Clipboard::new().ok());
        Self {
            clipboard,
            last_change_count: AtomicI64::new(0),
            echo_shield: EchoShield::new(),
            local_node,
        }
    }

    pub fn is_transient_password_uti(uti: &str) -> bool {
        uti == CONCEALED_TYPE || uti == AUTO_GENERATED_TYPE || uti == ONE_PASSWORD_TYPE
    }
}

impl ClipboardDriver for MacOSClipboardDriver {
    fn environment(&self) -> PlatformEnvironment {
        PlatformEnvironment::MacOS
    }

    fn read_clip(&self) -> Result<Option<CapturedClip>, PlatformError> {
        let mut guard = self.clipboard.lock().unwrap();
        let cb = match guard.as_mut() {
            Some(cb) => cb,
            None => return Ok(None),
        };

        if let Ok(text) = cb.get_text() {
            if !text.is_empty() {
                let bytes = text.into_bytes();
                let fp = compute_fingerprint(&bytes, &self.local_node);
                if self.echo_shield.should_suppress(&fp) {
                    return Ok(None);
                }
                return Ok(Some(CapturedClip {
                    content_type: ClipContentType::PlainTextUtf8,
                    data: bytes,
                    fingerprint: fp,
                }));
            }
        }
        Ok(None)
    }

    fn write_clip(&self, content_type: &ClipContentType, data: &[u8]) -> Result<(), PlatformError> {
        let mut guard = self.clipboard.lock().unwrap();
        let cb = match guard.as_mut() {
            Some(cb) => cb,
            None => {
                return Err(PlatformError::BackendUnavailable(
                    "Clipboard uninitialized".into(),
                ))
            }
        };

        let fp = compute_fingerprint(data, &self.local_node);
        self.echo_shield.record_injection(fp);

        if let ClipContentType::PlainTextUtf8 | ClipContentType::HtmlContent = content_type {
            let text = String::from_utf8_lossy(data);
            cb.set_text(text)
                .map_err(|e| PlatformError::BackendUnavailable(e.to_string()))?;
        }
        Ok(())
    }

    fn echo_shield(&self) -> &EchoShield {
        &self.echo_shield
    }
}
